# -*- coding: utf-8 -*-
"""Records every spoken sentence as a small audio file using the Mac's voices.

Steps to refresh the audio after changing text:
  1. python3 tools/build_*.py               (rebuild pages)
  2. run the site on localhost:8123 and tools/collect_server.py on :8124
  3. open http://localhost:8123/tools/collect.html  (saves tools/collected.json)
  4. python3 tools/make_audio.py            (records new lines, removes unused ones,
                                             writes audio-manifest.js)
Needs macOS with the voices listed in i18n.LANGS installed."""
import json, os, subprocess, tempfile, sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
import i18n

VOICE = {code: voice for code, _, _, voice in i18n.LANGS}
RATE = {"en": "165"}            # words per minute; others use the voice's own speed
BITRATE = "32000"

items = json.load(open(os.path.join(HERE, "collected.json"), encoding="utf-8"))
wanted = {}
for it in items:
    wanted[(it["lang"], it["hash"])] = it["text"]
print("unique lines:", len(wanted))

def record(key):
    lang, h = key
    out_dir = os.path.join(SITE, "audio", lang)
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, h + ".m4a")
    if os.path.exists(out) and os.path.getsize(out) > 0:
        return "skip"
    with tempfile.TemporaryDirectory() as td:
        txt = os.path.join(td, "t.txt")
        aiff = os.path.join(td, "t.aiff")
        with open(txt, "w", encoding="utf-8") as f:
            f.write(wanted[key])
        cmd = ["say", "-v", VOICE[lang], "-f", txt, "-o", aiff]
        if lang in RATE:
            cmd[1:1] = ["-r", RATE[lang]]
        subprocess.run(cmd, check=True)
        subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", BITRATE, aiff, out], check=True)
    return "new"

with ThreadPoolExecutor(max_workers=6) as ex:
    results = list(ex.map(record, wanted.keys()))
print("recorded:", results.count("new"), "already there:", results.count("skip"))

# remove recordings nothing uses any more
removed = 0
for lang in os.listdir(os.path.join(SITE, "audio")):
    d = os.path.join(SITE, "audio", lang)
    if not os.path.isdir(d):
        continue
    for fn in os.listdir(d):
        if fn.endswith(".m4a") and (lang, fn[:-4]) not in wanted:
            os.remove(os.path.join(d, fn)); removed += 1
print("removed unused:", removed)

keys = sorted(f"{l}:{h}" for (l, h) in wanted)
with open(os.path.join(SITE, "audio-manifest.js"), "w", encoding="utf-8") as f:
    f.write("/* generated by tools/make_audio.py: recorded lines, as language:hash */\nwindow.SS_AUDIO = {" + ",".join(f'"{k}":1' for k in keys) + "};\n")

total = 0
for root, _, files in os.walk(os.path.join(SITE, "audio")):
    total += sum(os.path.getsize(os.path.join(root, x)) for x in files)
print("manifest entries:", len(keys), " audio size: %.1f MB" % (total / 1e6))
